<?php

declare(strict_types=1);

function validate_public(
    string $root,
    string $publicDirectory,
    string $distDirectory,
    string $siteUrl,
    array $manifest,
    string $version,
): void {
    $pageSources = glob("$root/site/pages/*.php") ?: [];
    if ($pageSources === []) {
        fail('No site page sources were found.');
    }
    $slugs = array_map(static fn(string $path): string => basename($path, '.php'), $pageSources);
    sort($slugs);
    $pageNames = array_map(static fn(string $slug): string => "$slug.html", $slugs);
    exact_set(directory_entries($publicDirectory), array_merge($pageNames, ['assets', 'downloads', 'release.json', 'robots.txt', 'sitemap.xml']), 'Public root entries');
    exact_set(directory_entries("$publicDirectory/assets"), ['site.css', 'site.js'], 'Public assets');
    $cssName = $manifest['artifacts']['css'];
    $minifiedName = $manifest['artifacts']['cssMinified'];
    $apiName = $manifest['artifacts']['api'];
    $validatorName = $manifest['artifacts']['validator'];
    exact_set(directory_entries("$publicDirectory/downloads"), [$cssName, $minifiedName, $apiName, $validatorName], 'Public downloads');
    if (read_file("$publicDirectory/assets/site.css") !== read_file("$root/site/site.css")
        || read_file("$publicDirectory/assets/site.js") !== read_file("$root/site/site.js")) {
        fail('Public assets differ from site sources.');
    }
    validate_css_resources(read_file("$publicDirectory/assets/site.css"), "$publicDirectory/assets/site.css", "$publicDirectory/assets", $publicDirectory);
    foreach ([$cssName, $minifiedName, $apiName, $validatorName] as $name) {
        if (read_file("$publicDirectory/downloads/$name") !== read_file("$distDirectory/$name")) {
            fail("Public download differs from dist: $name");
        }
    }

    try {
        $release = json_decode(read_file("$publicDirectory/release.json"), true, 512, JSON_THROW_ON_ERROR);
    } catch (JsonException $error) {
        fail("Invalid release.json: {$error->getMessage()}");
    }
    if (!is_array($release)) {
        fail('release.json root must be an object.');
    }
    exact_keys($release, ['schemaVersion', 'name', 'version', 'releaseDate', 'changelog', 'artifacts'], [], 'release.json');
    if ($release['schemaVersion'] !== 1 || $release['name'] !== 'dctcss' || $release['version'] !== $version
        || $release['releaseDate'] !== current_release_date(read_file("$root/CHANGELOG.md"), $version)
        || $release['changelog'] !== "$siteUrl/changelog.html"
        || !is_array($release['artifacts'])) {
        fail('release.json identity, date or changelog is invalid.');
    }
    exact_keys($release['artifacts'], ['css', 'cssMinified', 'api', 'validator'], [], 'release.json artifacts');
    if ($release['artifacts'] !== [
        'css' => "$siteUrl/downloads/$cssName",
        'cssMinified' => "$siteUrl/downloads/$minifiedName",
        'api' => "$siteUrl/downloads/$apiName",
        'validator' => "$siteUrl/downloads/$validatorName",
    ]) {
        fail('release.json artifact URLs are invalid.');
    }

    $documents = [];
    $idsByPage = [];
    $htmlByPage = [];
    $documentation = '';
    foreach ($slugs as $slug) {
        $path = "$publicDirectory/$slug.html";
        [$document, $html] = load_html($path);
        $documents[$slug] = $document;
        $htmlByPage[$slug] = $html;
        $documentation .= "\n$html";
        if (!str_contains($html, 'Generated by site/build.php') || !str_contains($html, $version)) {
            fail("Public page has stale version or lacks its generated warning: $path");
        }
        if (!str_contains($html, 'href="changelog.html"')) {
            fail("Public navigation does not expose the changelog in $path.");
        }
        if (preg_match('/(?:demo\/|demo\.css|demo\.js|data-demo-|Generated by demo)/i', $html) === 1) {
            fail("Public page contains an active demo reference: $path");
        }
        $ids = [];
        foreach ($document->getElementsByTagName('*') as $element) {
            if (strtolower($element->tagName) === 'main') {
                $ancestor = $element->parentNode;
                while ($ancestor instanceof DOMElement) {
                    if (strtolower($ancestor->tagName) === 'main') {
                        fail("Nested main landmark in $path.");
                    }
                    $ancestor = $ancestor->parentNode;
                }
            }
            if ($element->hasAttribute('id')) {
                $id = $element->getAttribute('id');
                if ($id === '' || isset($ids[$id])) {
                    fail("Empty or duplicate id in $path: $id");
                }
                $ids[$id] = $element;
            }
        }
        $idsByPage[$slug] = $ids;
    }

    foreach ($documents as $slug => $document) {
        $path = "$publicDirectory/$slug.html";
        $ids = $idsByPage[$slug];
        $canonical = $slug === 'index' ? "$siteUrl/" : "$siteUrl/$slug.html";
        $xpath = new DOMXPath($document);
        $canonicalNodes = $xpath->query('//link[@rel="canonical"]');
        $descriptionNodes = $xpath->query('//meta[@name="description"]');
        $titleNodes = $xpath->query('//title');
        if ($canonicalNodes === false || $canonicalNodes->length !== 1 || $canonicalNodes->item(0)?->getAttribute('href') !== $canonical
            || $descriptionNodes === false || $descriptionNodes->length !== 1
            || $titleNodes === false || $titleNodes->length !== 1) {
            fail("Canonical, title or description is invalid in $path.");
        }
        $description = $descriptionNodes->item(0)?->getAttribute('content') ?? '';
        $title = $titleNodes->item(0)?->textContent ?? '';
        $expectedOg = ['og:type' => 'website', 'og:title' => $title, 'og:description' => $description, 'og:url' => $canonical];
        foreach ($expectedOg as $property => $expected) {
            $nodes = $xpath->query('//meta[@property="' . $property . '"]');
            if ($nodes === false || $nodes->length !== 1 || $nodes->item(0)?->getAttribute('content') !== $expected) {
                fail("Invalid $property in $path.");
            }
        }
        $repositoryUrl = 'https://github.com/doblejou/dctcss';
        $githubLinks = [$repositoryUrl];
        if ($slug === 'index') {
            $githubLinks[] = "$repositoryUrl/releases";
        }
        $expectedAbsoluteUrls = [$canonical, $canonical, ...$githubLinks];
        if ($slug === 'index') {
            $expectedAbsoluteUrls[] = "$siteUrl/downloads/$minifiedName";
        }
        preg_match_all('~https?://[^\s"<>&]+~', html_entity_decode($htmlByPage[$slug], ENT_QUOTES | ENT_HTML5, 'UTF-8'), $absoluteMatches);
        exact_set($absoluteMatches[0], $expectedAbsoluteUrls, "Absolute URLs in $path");

        $resourceAttributes = [
            'href' => ['a', 'area', 'link'],
            'src' => ['audio', 'embed', 'iframe', 'img', 'input', 'script', 'source', 'track', 'video'],
            'srcset' => ['img', 'source'],
            'poster' => ['video'],
            'data' => ['object'],
        ];
        foreach ($document->getElementsByTagName('*') as $element) {
            $tag = strtolower($element->tagName);
            foreach (['aria-labelledby', 'aria-describedby'] as $attribute) {
                if ($element->hasAttribute($attribute)) {
                    foreach (preg_split('/\s+/', trim($element->getAttribute($attribute))) as $target) {
                        if ($target === '' || !isset($ids[$target])) {
                            fail("Broken $attribute reference in $path: $target");
                        }
                    }
                }
            }
            foreach (['aria-controls', 'for', 'popovertarget'] as $attribute) {
                if ($element->hasAttribute($attribute) && !isset($ids[$element->getAttribute($attribute)])) {
                    fail("Broken $attribute reference in $path: " . $element->getAttribute($attribute));
                }
            }
            if ($element->hasAttribute('data-site-copy')) {
                $target = $element->getAttribute('data-site-copy');
                if (!isset($ids[$target]) || strtolower($ids[$target]->tagName) !== 'code') {
                    fail("Broken copy target in $path: $target");
                }
            }
            foreach ($resourceAttributes as $attribute => $allowedTags) {
                if (!$element->hasAttribute($attribute)) {
                    continue;
                }
                if (!in_array($tag, $allowedTags, true)) {
                    fail("Unsupported $attribute on <$tag> in $path.");
                }
                $reference = $element->getAttribute($attribute);
                if ($tag === 'a' && $attribute === 'href' && in_array($reference, $githubLinks, true)) {
                    continue;
                }
                if ($tag === 'link' && $attribute === 'href' && $element->getAttribute('rel') === 'canonical') {
                    continue;
                }
                if ($tag === 'link' && $attribute === 'href' && $element->getAttribute('rel') === 'icon' && $reference === 'data:,') {
                    continue;
                }
                $references = $attribute === 'srcset'
                    ? array_map(static fn(string $part): string => preg_split('/\s+/', trim($part), 2)[0] ?? '', explode(',', $reference))
                    : [$reference];
                foreach ($references as $item) {
                    public_reference($item, $attribute, $slug, $path, $publicDirectory, $idsByPage);
                }
            }
            if ($element->hasAttribute('style')) {
                validate_css_resources($element->getAttribute('style'), "$path style attribute", $publicDirectory, $publicDirectory);
            }
        }
        foreach ($document->getElementsByTagName('code') as $code) {
            if ($code->parentNode instanceof DOMElement && strtolower($code->parentNode->tagName) === 'pre' && str_contains($code->textContent, 'data-site-')) {
                fail("Copyable snippet contains data-site-* in $path.");
            }
            if ($code->parentNode instanceof DOMElement && strtolower($code->parentNode->tagName) === 'pre' && $code->hasAttribute('id')) {
                validate_copyable_snippet($code->textContent, $manifest, "$path#" . $code->getAttribute('id'));
            }
        }
    }

    if (version_compare($version, '1.4.0', '>=')) {
        if (!isset($documents['application'])) {
            fail('The public reference application page is missing.');
        }
        validate_reference_application($documents['application'], "$publicDirectory/application.html");
        if (!isset($documents['fundamentals'])) {
            fail('The fundamentals page is missing.');
        }
        validate_documented_token_values($root, $documents['fundamentals'], $manifest);
    }

    foreach (['classNames', 'modifierNames', 'tokens', 'animations', 'attributeNames'] as $section) {
        foreach ($manifest[$section] as $name) {
            if (!str_contains($documentation, $name)) {
                fail("Public documentation does not cover $name.");
            }
        }
    }
    validate_documented_api($documentation, $manifest, 'Public documentation');

    $robots = "User-agent: *\nAllow: /\nSitemap: $siteUrl/sitemap.xml\n";
    if (read_file("$publicDirectory/robots.txt") !== $robots) {
        fail('robots.txt is invalid.');
    }
    $previous = libxml_use_internal_errors(true);
    $sitemap = new DOMDocument();
    $loaded = $sitemap->load("$publicDirectory/sitemap.xml", LIBXML_NONET);
    libxml_clear_errors();
    libxml_use_internal_errors($previous);
    if (!$loaded) {
        fail('sitemap.xml is invalid XML.');
    }
    $sitemapUrls = [];
    foreach ($sitemap->getElementsByTagName('loc') as $location) {
        $sitemapUrls[] = $location->textContent;
    }
    $expectedUrls = array_map(static fn(string $slug): string => $slug === 'index' ? "$siteUrl/" : "$siteUrl/$slug.html", $slugs);
    exact_set($sitemapUrls, $expectedUrls, 'Sitemap URLs');

    $changelogPage = $htmlByPage['changelog'] ?? '';
    preg_match_all('/^## (\d+\.\d+\.\d+) - (\d{4}-\d{2}-\d{2})$/m', read_file("$root/CHANGELOG.md"), $releaseHeadings, PREG_SET_ORDER);
    if ($releaseHeadings === []) {
        fail('CHANGELOG.md has no release entries.');
    }
    foreach ($releaseHeadings as $heading) {
        if (!str_contains($changelogPage, $heading[1]) || !str_contains($changelogPage, $heading[2])) {
            fail("Public changelog does not cover release {$heading[1]}.");
        }
    }

    $index = $htmlByPage['index'];
    foreach ([$cssName, $minifiedName] as $name) {
        $download = "$distDirectory/$name";
        $bytes = filesize($download);
        if ($bytes === false
            || !str_contains($index, "$bytes bytes")
            || !str_contains($index, ">" . $version . "<")) {
            fail("Landing metadata is invalid for $name.");
        }
    }
    $minifiedContents = read_file("$distDirectory/$minifiedName");
    $gzip = gzencode($minifiedContents, 9, ZLIB_ENCODING_GZIP);
    if ($gzip === false || !str_contains($index, strlen($gzip) . ' bytes')) {
        fail('Landing metadata lacks the current minified gzip size.');
    }
    $install = '<link rel="stylesheet" href="' . $siteUrl . '/downloads/' . $minifiedName . '">';
    if (!str_contains(html_entity_decode($index, ENT_QUOTES | ENT_HTML5, 'UTF-8'), $install)) {
        fail('The absolute installation snippet is missing or invalid.');
    }
}
